#!/usr/bin/env pwsh
# ABOUTME: Installs the Snapclip capture script (Windows) into %LOCALAPPDATA%\Programs\Snapclip.
# ABOUTME: Creates a Start Menu shortcut carrying a global hotkey, launched without a console flash.

[CmdletBinding()]
param(
    # Windows registers this globally as long as the shortcut lives in the Start Menu.
    [string] $Hotkey = 'CTRL+ALT+S'
)

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$appName    = 'Snapclip'
$sourceDir  = Join-Path $PSScriptRoot 'src'
$installDir = Join-Path $env:LOCALAPPDATA "Programs\$appName"
$scriptPath = Join-Path $installDir 'snapclip.ps1'
$launchPath = Join-Path $installDir 'snapclip-launch.vbs'
$linkPath   = Join-Path ([Environment]::GetFolderPath('Programs')) "$appName.lnk"

if ($Hotkey -notmatch '^(CTRL|ALT|SHIFT)\+') {
    throw "Hotkey '$Hotkey' needs at least one modifier, e.g. CTRL+ALT+S."
}

# Prefer PowerShell 7, but Windows PowerShell is always present as a fallback.
$powershell = (Get-Command pwsh.exe -ErrorAction SilentlyContinue).Source
if (-not $powershell) {
    $powershell = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
}

New-Item -ItemType Directory -Force -Path $installDir | Out-Null
Copy-Item -LiteralPath (Join-Path $sourceDir 'snapclip.ps1') -Destination $scriptPath -Force

# A shortcut pointing straight at PowerShell flashes a console window on every
# capture. wscript.exe has no console of its own, so it starts the hidden shell
# silently. -ExecutionPolicy Bypass keeps the default Restricted policy from
# blocking our own installed script.
$launcher = @"
' ABOUTME: Starts the Snapclip capture script with no console window.
' ABOUTME: Generated by install.ps1 - change the installer, not this file.
Set shell = CreateObject("WScript.Shell")
shell.Run """$powershell"" -NoProfile -STA -ExecutionPolicy Bypass -WindowStyle Hidden -File ""$scriptPath""", 0, False
"@
Set-Content -LiteralPath $launchPath -Value $launcher -Encoding ASCII

$shell = New-Object -ComObject WScript.Shell
$shortcut = $shell.CreateShortcut($linkPath)
$shortcut.TargetPath       = Join-Path $env:SystemRoot 'System32\wscript.exe'
$shortcut.Arguments        = """$launchPath"""
$shortcut.WorkingDirectory = $installDir
$shortcut.Description      = 'Capture a screenshot and copy its path to the clipboard'
$shortcut.WindowStyle      = 7
$shortcut.Hotkey           = $Hotkey
$shortcut.Save()

@"

Installed: $installDir
Shortcut : $linkPath  ($Hotkey)

Next steps
----------
1. Press $Hotkey. The snip overlay appears; drag a region, or use the toolbar to
   pick a whole window. The PNG path lands on your clipboard, ready to paste.

2. Turn OFF Snipping Tool's own auto-save, or every capture is stored twice:
       Snipping Tool -> Settings -> "Automatically save original screenshots"

Captures save to $([Environment]::GetFolderPath('MyPictures'))\snapclip by default.
Override in ~\.config\snapclip\config with:  SCREENSHOT_DIR=C:\some\path

To uninstall, delete the two paths listed above.
"@
